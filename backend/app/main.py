@app.post("/api/auth/register", status_code=201)
def register(
    item: AccountInput,
    response: Response,
    _: None = Depends(require_same_origin),
) -> dict[str, str]:
    try:
        with database() as connection:
            user = connection.execute(
                """
                INSERT INTO users (email, password_hash)
                VALUES (%s, %s)
                RETURNING id, email, session_version
                """,
                (
                    item.email,
                    PASSWORD_HASHER.hash(item.password),
                ),
            ).fetchone()

    except IntegrityError:
        raise HTTPException(
            status_code=409,
            detail="An account with this email already exists.",
        ) from None

    set_session_cookie(
        response,
        user["id"],
        user["session_version"],
    )

    return {
        "id": str(user["id"]),
        "email": user["email"],
    }


@app.post("/api/auth/login")
def login(
    item: LoginInput,
    response: Response,
    _: None = Depends(require_same_origin),
) -> dict[str, str]:
    with database() as connection:
        user = connection.execute(
            """
            SELECT id, email, password_hash, session_version
            FROM users
            WHERE email = %s
            """,
            (item.email,),
        ).fetchone()

    password_hash = (
        user["password_hash"] if user else PASSWORD_HASHER_DUMMY
    )
    password_matches = PASSWORD_HASHER.verify(
        item.password,
        password_hash,
    )

    if user is None or not password_matches:
        raise HTTPException(
            status_code=401,
            detail="Email or password is incorrect.",
        )

    set_session_cookie(
        response,
        user["id"],
        user["session_version"],
    )

    return {
        "id": str(user["id"]),
        "email": user["email"],
    }


