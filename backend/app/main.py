@app.get("/api/dashboard")
def dashboard(
    month: str = Query(
        default_factory=lambda: date.today().strftime("%Y-%m")
    ),
    user: dict = Depends(get_current_user),
):
    start, end = month_bounds(month)

    with database() as connection:
        totals = connection.execute(
            """
            SELECT
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Income'
                ), 0) AS income,
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Expense'
                ), 0) AS expenses
            FROM transactions
            WHERE user_id = %s
            """,
            (user["id"],),
        ).fetchone()

        monthly = connection.execute(
            """
            SELECT
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Income'
                ), 0) AS income,
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Expense'
                ), 0) AS expenses
            FROM transactions
            WHERE user_id = %s
              AND transaction_date >= %s
              AND transaction_date < %s
            """,
            (user["id"], start, end),
        ).fetchone()

        budget = connection.execute(
            """
            SELECT budget_amount
            FROM account_monthly_budgets
            WHERE user_id = %s AND month = %s
            """,
            (user["id"], month),
        ).fetchone()

        recent = connection.execute(
            """
            SELECT id, transaction_type, category, amount,
                   transaction_date, description
            FROM transactions
            WHERE user_id = %s
            ORDER BY transaction_date DESC, id DESC
            LIMIT 8
            """,
            (user["id"],),
        ).fetchall()

    return {
        "income": totals["income"],
        "expenses": totals["expenses"],
        "balance": totals["income"] - totals["expenses"],
        "month": month,
        "monthly_income": monthly["income"],
        "monthly_expenses": monthly["expenses"],
        "monthly_budget": budget["budget_amount"] if budget else None,
        "recent_transactions": [
            serialize_transaction(row) for row in recent
        ],
    }


@app.get("/api/transactions")
def list_transactions(
    search: str = "",
    transaction_type: Literal["All", "Income", "Expense"] = "All",
    category: str = "All",
    start_date: date | None = None,
    end_date: date | None = None,
    limit: int = Query(default=500, ge=1, le=2000),
    offset: int = Query(default=0, ge=0),
    user: dict = Depends(get_current_user),
):
    where, parameters = transaction_filters(
        user["id"],
        search,
        transaction_type,
        category,
        start_date,
        end_date,
    )

    with database() as connection:
        total = connection.execute(
            f"SELECT COUNT(*) AS total FROM transactions WHERE {where}",
            parameters,
        ).fetchone()["total"]

        rows = connection.execute(
            f"""
            SELECT id, transaction_type, category, amount,
                   transaction_date, description
            FROM transactions
            WHERE {where}
            ORDER BY transaction_date DESC, id DESC
            LIMIT %s OFFSET %s
            """,
            [*parameters, limit, offset],
        ).fetchall()

        categories = [
            row["category"]
            for row in connection.execute(
                """
                SELECT DISTINCT category
                FROM transactions
                WHERE user_id = %s
                  AND category IS NOT NULL
                  AND category <> ''
                ORDER BY LOWER(category), category
                """,
                (user["id"],),
            ).fetchall()
        ]

    return {
        "items": [serialize_transaction(row) for row in rows],
        "total": total,
        "categories": categories,
    }


