@app.get("/api/budgets")
def get_budget(
    month: str = Query(
        default_factory=lambda: date.today().strftime("%Y-%m")
    ),
    user: dict = Depends(get_current_user),
):
    start, end = month_bounds(month)

    with database() as connection:
        budget = connection.execute(
            """
            SELECT budget_amount
            FROM account_monthly_budgets
            WHERE user_id = %s AND month = %s
            """,
            (user["id"], month),
        ).fetchone()

        spent = connection.execute(
            """
            SELECT COALESCE(SUM(amount), 0) AS spent
            FROM transactions
            WHERE user_id = %s
              AND transaction_type = 'Expense'
              AND transaction_date >= %s
              AND transaction_date < %s
            """,
            (user["id"], start, end),
        ).fetchone()["spent"]

    amount = budget["budget_amount"] if budget else None

    return {
        "month": month,
        "budget": amount,
        "spent": spent,
        "remaining": amount - spent if amount is not None else None,
        "progress": spent / amount if amount else 0,
    }


@app.put("/api/budgets/{month}")
def save_budget(
    month: str,
    item: BudgetInput,
    _: None = Depends(require_same_origin),
    user: dict = Depends(get_current_user),
):
    month_bounds(month)

    if not math.isfinite(item.amount):
        raise HTTPException(
            status_code=422,
            detail="Budget must be a finite amount.",
        )

    with database() as connection:
        connection.execute(
            """
            INSERT INTO account_monthly_budgets (
                user_id, month, budget_amount
            )
            VALUES (%s, %s, %s)
            ON CONFLICT (user_id, month)
            DO UPDATE SET budget_amount = EXCLUDED.budget_amount
            """,
            (user["id"], month, item.amount),
        )

    return get_budget(month, user)


@app.get("/api/analytics")
def analytics(
    period: Literal["all", "last12", "year"] = "all",
    user: dict = Depends(get_current_user),
):
    today = date.today()

    conditions = ["user_id = %s"]
    parameters: list[object] = [user["id"]]

    if period == "last12":
        month_index = today.year * 12 + today.month - 1 - 11
        first_month = date(
            month_index // 12,
            month_index % 12 + 1,
            1,
        )
        conditions.append("transaction_date >= %s")
        conditions.append("transaction_date <= %s")
        parameters.extend([
            first_month,
            today,
        ])

    elif period == "year":
        year_start = date(today.year, 1, 1)
        next_year = date(today.year + 1, 1, 1)
        conditions.append("transaction_date >= %s")
        conditions.append("transaction_date < %s")
        parameters.extend([
            year_start,
            next_year,
        ])

    where = " AND ".join(conditions)

    with database() as connection:
        categories = connection.execute(
            f"""
            SELECT category, SUM(amount) AS amount
            FROM transactions
            WHERE {where}
              AND transaction_type = 'Expense'
            GROUP BY category
            ORDER BY amount DESC
            """,
            parameters,
        ).fetchall()

        months = connection.execute(
            f"""
            SELECT
                TO_CHAR(DATE_TRUNC('month', transaction_date), 'YYYY-MM')
                    AS month,
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Income'
                ), 0) AS income,
                COALESCE(SUM(amount) FILTER (
                    WHERE transaction_type = 'Expense'
                ), 0) AS expenses
            FROM transactions
            WHERE {where}
            GROUP BY DATE_TRUNC('month', transaction_date)
            ORDER BY DATE_TRUNC('month', transaction_date)
            """,
            parameters,
        ).fetchall()

    return {
        "categories": [
            {
                "category": row["category"],
                "amount": row["amount"],
            }
            for row in categories
        ],
        "months": [dict(row) for row in months],
    }


def csv_safe(value: object) -> object:
    if isinstance(value, str) and value.startswith(
        ("=", "+", "-", "@", "\t", "\r")
    ):
        return "'" + value

    return value


@app.get("/api/transactions/export.csv")
def export_transactions(
    search: str = "",
    transaction_type: Literal["All", "Income", "Expense"] = "All",
    category: str = "All",
    start_date: date | None = None,
    end_date: date | None = None,
    user: dict = Depends(get_current_user),
):
    where, parameters = transaction_filters(
        user["id"],
        search,
        transaction_type,
        category,
        start_date,
        end_date,
    )

    with database() as connection:
        rows = connection.execute(
            f"""
            SELECT id, transaction_type, category, amount,
                   transaction_date, description
            FROM transactions
            WHERE {where}
            ORDER BY transaction_date DESC, id DESC
            """,
            parameters,
        ).fetchall()

    output = io.StringIO(newline="")
    writer = csv.writer(output)

    writer.writerow((
        "ID",
        "Type",
        "Category",
        "Amount",
        "Date",
        "Description",
    ))

    for row in rows:
        values = [
            row["id"],
            row["transaction_type"],
            row["category"],
            row["amount"],
            row["transaction_date"].isoformat(),
            row["description"],
        ]
        writer.writerow(csv_safe(value) for value in values)

    return Response(
        content="\ufeff" + output.getvalue(),
        media_type="text/csv; charset=utf-8",
        headers={
            "Content-Disposition": 'attachment; filename="transactions.csv"'
        },
    )
