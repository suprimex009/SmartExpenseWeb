def session_serializer() -> URLSafeTimedSerializer:
    if len(SESSION_SECRET_KEY) < 32:
        raise HTTPException(
            status_code=503,
            detail="Server authentication is not configured. Set MONETA_SECRET_KEY.",
        )
    return URLSafeTimedSerializer(
        SESSION_SECRET_KEY,
        salt="moneta-auth-v1",
    )


def require_same_origin(request: Request) -> None:
    origin = request.headers.get("origin", "").rstrip("/")
    if not origin or origin not in ALLOWED_ORIGINS:
        raise HTTPException(
            status_code=403,
            detail="Request origin is not allowed.",
        )


def database_url() -> str:
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Configure your Supabase PostgreSQL connection string."
        )

    # Supabase requires SSL. Add sslmode=require if it is not already specified.
    if "sslmode=" not in DATABASE_URL.lower():
        separator = "&" if "?" in DATABASE_URL else "?"
        return f"{DATABASE_URL}{separator}sslmode=require"

    return DATABASE_URL


@contextmanager
def database() -> Generator[Connection, None, None]:
    """Open a PostgreSQL connection and commit or roll back the transaction."""
    connection = None

    try:
        connection = connect(
            database_url(),
            row_factory=dict_row,
            connect_timeout=10,
        )
        yield connection
        connection.commit()
    except IntegrityError:
        if connection is not None:
            connection.rollback()
        raise
    except Error as error:
        if connection is not None:
            connection.rollback()
        raise HTTPException(
            status_code=500,
            detail="A database operation failed. Please try again.",
        ) from error

    except Exception:
        if connection is not None:
            connection.rollback()
        raise

    finally:
        if connection is not None:
            connection.close()


def create_schema() -> None:
    """Create the fresh Moneta PostgreSQL schema if it does not exist."""
    statements = [
        """
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            session_version INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS transactions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            transaction_type TEXT NOT NULL
                CHECK (transaction_type IN ('Income', 'Expense')),
            category TEXT NOT NULL,
            amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
            transaction_date DATE NOT NULL,
            description TEXT,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS account_monthly_budgets (
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            month TEXT NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
            budget_amount DOUBLE PRECISION NOT NULL CHECK (budget_amount > 0),
            PRIMARY KEY (user_id, month)
        )
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_transactions_user_date
        ON transactions(user_id, transaction_date DESC, id DESC)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_transactions_user_category
        ON transactions(user_id, category)
        """,
    ]

    try:
        with database() as connection:
            for statement in statements:
                connection.execute(statement)
    except HTTPException as error:
        raise RuntimeError(
            "Could not create the Moneta PostgreSQL database schema. "
            "Check DATABASE_URL and your Supabase connection."
        ) from error


def verify_database() -> None:
    if len(SESSION_SECRET_KEY) < 32:
        raise RuntimeError(
            "MONETA_SECRET_KEY must be configured with at least 32 characters."
        )

    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Set it to your Supabase PostgreSQL connection string."
        )

    try:
        with database() as connection:
            required_tables = {
                "users",
                "transactions",
                "account_monthly_budgets",
            }

            rows = connection.execute(
                """
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
                """
            ).fetchall()

            existing_tables = {row["table_name"] for row in rows}
            missing = required_tables - existing_tables

            if missing:
                raise RuntimeError(
                    "Required database tables are missing: "
                    + ", ".join(sorted(missing))
                )

            user_columns = {
                row["column_name"]
                for row in connection.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = 'users'
                    """
                ).fetchall()
            }

            transaction_columns = {
                row["column_name"]
                for row in connection.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = 'transactions'
                    """
                ).fetchall()
            }

            budget_columns = {
                row["column_name"]
                for row in connection.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public'
                      AND table_name = 'account_monthly_budgets'
                    """
                ).fetchall()
            }

            if not {"id", "email", "password_hash", "session_version"} <= user_columns:
                raise RuntimeError("The users table has an unexpected schema.")

            if not {
                "id", "transaction_type", "category", "amount",
                "transaction_date", "description", "user_id",
            } <= transaction_columns:
                raise RuntimeError("The transactions table has an unexpected schema.")

            if not {
                "user_id", "month", "budget_amount",
            } <= budget_columns:
                raise RuntimeError("The budgets table has an unexpected schema.")

    except HTTPException as error:
        raise RuntimeError(
            "Could not verify the Supabase PostgreSQL database."
        ) from error


def initialize_database() -> None:
    create_schema()
    verify_database()


def get_current_user(request: Request) -> dict:
    token = request.cookies.get(SESSION_COOKIE_NAME)

    if not token:
        raise HTTPException(
            status_code=401,
            detail="Please sign in to continue.",
        )

    try:
        session = session_serializer().loads(
            token,
            max_age=SESSION_MAX_AGE,
        )
        user_id = int(session["user_id"])
        session_version = int(session["session_version"])
    except (BadSignature, KeyError, TypeError, ValueError):
        raise HTTPException(
            status_code=401,
            detail="Your session expired. Please sign in again.",
        ) from None

    with database() as connection:
        user = connection.execute(
            """
            SELECT id, email, session_version
            FROM users
            WHERE id = %s
            """,
            (user_id,),
        ).fetchone()

    if user is None or user["session_version"] != session_version:
        raise HTTPException(
            status_code=401,
            detail="Your account is unavailable. Please sign in again.",
        )

    return user


def set_session_cookie(
    response: Response,
    user_id: int,
    session_version: int,
) -> None:
    token = session_serializer().dumps({
        "user_id": user_id,
        "session_version": session_version,
    })

    response.set_cookie(
        SESSION_COOKIE_NAME,
        token,
        max_age=SESSION_MAX_AGE,
        httponly=True,
        secure=SESSION_COOKIE_SECURE,
        samesite="none",
        path="/",
    )


def validate_email(value: str) -> str:
    normalized = value.strip().lower()

    if (
        len(normalized) > 254
        or not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", normalized)
    ):
        raise ValueError("Enter a valid email address.")

    return normalized


def month_bounds(month: str) -> tuple[date, date]:
    try:
        year, month_number = (
            int(part) for part in month.split("-")
        )
        start = date(year, month_number, 1)
    except (ValueError, TypeError):
        raise HTTPException(
            status_code=422,
            detail="Month must use YYYY-MM format.",
        ) from None

    if start.strftime("%Y-%m") != month:
        raise HTTPException(
            status_code=422,
            detail="Month must use YYYY-MM format.",
        )

    if month_number == 12:
        next_month = date(year + 1, 1, 1)
    else:
        next_month = date(year, month_number + 1, 1)

    return start, next_month


def transaction_filters(
    user_id: int,
    search: str,
    transaction_type: str,
    category: str,
    start_date: date | None,
    end_date: date | None,
) -> tuple[str, list[object]]:
    conditions = ["user_id = %s"]
    parameters: list[object] = [user_id]

    search = search.strip()

    if search:
        conditions.append(
            """
            (
                POSITION(LOWER(%s) IN LOWER(CAST(id AS TEXT))) > 0
                OR POSITION(LOWER(%s) IN LOWER(transaction_type)) > 0
                OR POSITION(LOWER(%s) IN LOWER(category)) > 0
                OR POSITION(LOWER(%s) IN LOWER(CAST(amount AS TEXT))) > 0
                OR POSITION(LOWER(%s) IN LOWER(transaction_date::TEXT)) > 0
                OR POSITION(LOWER(%s) IN LOWER(COALESCE(description, ''))) > 0
            )
            """
        )
        parameters.extend([search] * 6)

    if transaction_type != "All":
        conditions.append("transaction_type = %s")
        parameters.append(transaction_type)

    if category != "All":
        conditions.append("category = %s")
        parameters.append(category)

    if start_date:
        conditions.append("transaction_date >= %s")
        parameters.append(start_date)

    if end_date:
        conditions.append("transaction_date <= %s")
        parameters.append(end_date)

    if start_date and end_date and start_date > end_date:
        raise HTTPException(
            status_code=422,
            detail="The start date must be on or before the end date.",
        )

    return " AND ".join(conditions), parameters


def serialize_transaction(row: dict) -> dict[str, object]:
    transaction_date = row["transaction_date"]

    if isinstance(transaction_date, date):
        transaction_date = transaction_date.isoformat()

    return {
        "id": row["id"],
        "transaction_type": row["transaction_type"],
        "category": row["category"],
        "amount": row["amount"],
        "transaction_date": transaction_date,
        "description": row["description"] or "",
    }


